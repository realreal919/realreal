def flav(t):
    for k in sorted(FL, key=len, reverse=True):
        if k in t:
            return FL[k]

def from_variant(variant, total, size):
    """由規格字串解析。

    「其他口味(銀杏水蜜桃口味限N入)」一律不在此解析 —— 字串裡的「銀杏水蜜桃」
    只是數量上限的說明，不是客人選的口味，實際口味寫在備註欄。少了這道防線
    會把整組都算成銀杏（2026-09-01 發現，出貨單與進出明細表都曾受影響）。

    「任選N袋（不含銀杏水蜜桃…）」同理：裡面的「銀杏水蜜桃」是排除說明。少了「不含」
    這一條，備註解析失敗時整組會被算成銀杏水蜜桃（2026-10-06 發現，5 袋組就是這樣）。
    """
    if "其他" in variant or "不含" in variant:
        return None
    v = variant.replace("選擇風味:", "").strip()
    m = re.search(r"各\s*(\d+)", v)
    names = re.split(r"[+＋．・、/]", re.sub(r"各\s*\d+\s*[入包]?", "", v))
    fl = list(dict.fromkeys([flav(n) for n in names if flav(n)]))
    if not fl:
        return None
    if m:
        c = {f: int(m.group(1)) for f in fl}
    elif len(fl) == 1:
        c = {fl[0]: total}
    else:
        return None
    return {f"{f}蛋白粉{size}": n for f, n in c.items()} if sum(c.values()) == total else None

def from_notes(notes, total, size):
    if not notes:
        return None
    c = collections.Counter()
    # 分隔符含 + 與全形＋：「原味+1/可可+1/草莓+3」是常見寫法，少了它整段湊不出
    # 總數，會被判定無效而退回規格的預設比例 —— #10000206 就因此漏掉客人指定的
    # 銀杏水蜜桃。「草莓+可可」這種口味並列不受影響，分隔符後面必須接數字才算。
    for m in re.finditer(r"([\u4e00-\u9fff]+)\s*[*xX×+＋]?\s*(\d+)", notes):
        f = flav(m.group(1))
        if f:
            c[f] += int(m.group(2))
    return {f"{f}蛋白粉{size}": n for f, n in c.items()} if c and sum(c.values()) == total else None

