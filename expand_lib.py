def expand_item(order_no, name, variant, qty, notes):
    """回傳 {品名: 包數}；無法判斷時回傳 None。"""
    ov = OVERRIDE.get((order_no, name, variant or ""))
    if ov:
        # OVERRIDE 是「這一行的最終總數」，不再乘上 qty。人工核對備註時寫下來的
        # 本來就是最後要出幾包，而不是「每組幾包」—— #10000221 買了 2 組 3 入袋、
        # 備註「6種口味各一」，六種各一袋就是全部，根本沒辦法拆成兩組相同的 3 袋。
        # 舊寫法會把它乘成 12 袋。既有的 override 全部都是 qty=1（已核對），
        # 所以這個改動不影響任何一筆。
        return dict(ov)
    # 2026-09-21 起的同口味隨身包組（qty 是組數，每組包數寫在規格名稱裡）：
    #   各口味單包頁的「2入組」規格，以及「同口味 2 入｜隨身包體驗組」的「選擇風味: X 2入」。
    #   當天先上過 3 入組、隨即改成 2 入 —— 包數從名稱讀，兩種都認得。
    m = re.match(r"(\d+)入組", variant or "")
    if name in SIMPLE and m:
        return {SIMPLE[name]: int(m.group(1)) * qty}
    if name in ("同口味 2 入｜50克隨身包自由配", "同口味 2 入｜50克隨身包體驗組","同口味 2 入｜隨身包體驗組", "50克隨身包 3 入組｜任選口味"):
        v = (variant or "").replace("選擇風味:", "").strip()
        n = re.search(r"(\d+)入", v)
        for key, code in SACHET_FLAVOURS:
            if v.startswith(key) and n:
                return {code: int(n.group(1)) * qty}
        return None
    if name in SIMPLE:
        return {SIMPLE[name]: qty}
    # 通路商訂單的贈品會在品名後面加括號註記（例：「…｜柔光歲月（贈品・試喝）」），
    # 去掉括號就是原本的商品。
    stripped = re.sub(r"（[^）]*）$", "", name).strip()
    if stripped in SIMPLE:
        return {SIMPLE[stripped]: qty}
    if name == "入門推薦 | 6入嘗鮮組合":
        return {k: v * qty for k, v in SAMPLER6.items()}
    if name == "誠真心意 | 滋養禮盒":
        return {k: v * qty for k, v in GIFTSET.items()}
    if name in BUNDLE:
        total, size = BUNDLE[name]
        # 備註優先於規格。客人點了一個固定比例的規格、又在備註寫下自己要的口味，
        # 那備註才是他要的東西 —— #10000193 點「全口味各2包」卻在備註寫
        # 「原味x2 可可x2 草莓x3 芝麻藍莓x3」，他不要杏仁火龍果。
        #
        # 原本的順序是規格優先，只有規格解析不出來才看備註，於是這種改單一律被
        # 忽略；#10000106（要可可/草莓/原味各10，出成草莓15+芝麻15）和 #10000130
        # （要銀杏2/芝麻4/草莓2/可可2，出成可可5+草莓5）就是這樣出錯的。
        #
        # 敢把備註放前面，是因為 from_notes 的門檻很嚴：解析出來的包數必須「剛好」
        # 等於這個組合的總數才算數。閒聊、道謝、「10/3前要收到」都湊不出總數，
        # 會回 None 然後退回規格。
        # 三段式，由最貼近客人意圖的往後退：
        #   1. 備註寫成「口味 x 數量」→ from_notes
        #   2. 備註寫成「A+B+C 各N包」→ 借用 from_variant 的「各N」解析，因為
        #      客人常常直接照規格的句型寫（#10000213：「杏仁火龍果+黑芝麻藍莓+
        #      銀杏水蜜桃, 各10包」）。誤判的風險由「總數必須剛好相符」擋住。
        #   3. 都不行才回頭看客人點的規格
        c = (
            from_notes(notes, total, size)
            or from_notes_each(notes, total, size)
            or ginkgo_plus_other(variant, notes, total, size)
            or from_variant(variant or "", total, size)
            # 規格名稱直接寫出每個口味的包數（例：「偏心果實 銀杏水蜜桃x2．草莓x2…」）。
            # from_variant 只認得「各N」，這種逐一列出的靠 from_notes 的「口味＋數量」解析，
            # 一樣要求加總剛好等於組合總數。
            or from_notes(variant, total, size)
            or from_notes_list(notes, total, size)
        )
        return {k: v * qty for k, v in c.items()} if c else None
    return None
