def from_notes_each(notes, total, size):
    """備註寫成「A+B+C 各N包」的句型。

    客人常直接照規格的講法寫，例如 #10000213 的「杏仁火龍果+黑芝麻藍莓+
    銀杏水蜜桃, 各10包」。from_notes 只認「口味＋數量」成對，抓不到這種。

    這裡刻意**不**沿用 from_variant：那支函式在只認出一種口味時，會把整組數量
    全部給那一種。規格字串是系統產生的、格式可控，那樣做沒問題；但備註是客人
    自由書寫，同樣的邏輯會把「在Lynn的影片看到她分享喝到草莓口味…」解讀成
    可可 10 包（實測 9 筆歷史訂單被改壞）。

    所以三個條件缺一不可：
      1. 必須出現明確的「各N」
      2. 必須認出兩種以上口味 —— 一種口味時無從判斷是不是真的整組都要它
      3. 口味數 × N 必須剛好等於組合總數
    """
    if not notes:
        return None
    m = re.search(r"各\s*(\d+)", notes)
    if not m:
        return None
    per = int(m.group(1))
    text = re.sub(r"各\s*\d+\s*[入包]?", "", notes)
    fl = list(dict.fromkeys(f for f in (flav(t) for t in re.split(r"[+＋．・、,，/\s]+", text)) if f))
    if len(fl) < 2 or len(fl) * per != total:
        return None
    return {f"{f}蛋白粉{size}": per for f in fl}


def from_notes_list(notes, total, size):
    """備註只列口味、沒寫數量：「三入組：原味、果真草莓、芝麻藍莓」→ 各 1。

    只在「認出的口味數剛好等於組合總數」時才算數，而且備註要短、不能出現數字
    —— 有數字代表客人自己配了比例，那是 from_notes 的事；長備註可能是閒聊裡
    提到口味（見 from_notes_each 的說明）。
    """
    if not notes:
        return None
    compact = re.sub(r"[\s,，、。：:／/．・]+", "", notes)
    if len(compact) > 30 or re.search(r"\d", compact):
        return None
    fl = list(dict.fromkeys(f for f in (flav(t) for t in re.split(r"[+＋．・、,，:：／/\s]+", notes)) if f))
    if len(fl) != total:
        return None
    return {f"{f}蛋白粉{size}": 1 for f in fl}


def ginkgo_plus_other(variant, notes, total, size):
    """「銀杏水蜜桃．其他口味 各30入」：一半固定是銀杏，另一半看備註。

    備註只會寫「另一半」要什麼 —— 最常見的是只寫一個口味名稱（「草莓」），
    也可能寫「草莓15 可可15」或「草莓+可可 各15」。銀杏那一半是規格本身
    決定的，備註裡不會重寫，所以 from_notes 拿 60 去比永遠湊不到。
    """
    # 兩種寫法：舊的「銀杏水蜜桃．其他口味 各30入」（一半一半），以及 2026-09-18
    # 改成的「銀杏水蜜桃15入．其他口味任選45入」。per 是固定的銀杏包數。
    # 訂單上存的是下單當時的規格名稱，所以兩種都要認得。
    m = (re.search(r"銀杏水蜜桃．其他口味\s*各\s*(\d+)", variant or "")
         or re.search(r"銀杏水蜜桃\s*(\d+)\s*[入袋]\s*[．・+＋]?\s*其他口味", variant or ""))
    if not m or not notes:
        return None
    per = int(m.group(1))
    rest = total - per
    c = from_notes(notes, rest, size) or from_notes_each(notes, rest, size)
    if c is None:
        # 只寫一個口味名稱。限定短備註 —— 長備註可能是閒聊裡剛好提到某個口味
        # （見 from_notes_each 的說明：曾有 9 筆歷史訂單因此被解讀錯）。
        compact = re.sub(r"[\s,，、。.!！~～]+", "", notes)
        fl = list(dict.fromkeys(f for f in (flav(t) for t in re.split(r"[+＋．・、,，/\s]+", notes)) if f))
        if len(fl) == 1 and fl[0] != "銀杏" and len(compact) <= 12:
            c = {f"{fl[0]}蛋白粉{size}": rest}
    if c is None:
        return None
    out = dict(c)
    key = f"銀杏蛋白粉{size}"
    out[key] = out.get(key, 0) + per
    return out if sum(out.values()) == total else None


